// $IMG2_HOME/runtime/selectors.json (the contract with the core) and env.sh (for humans).
import fs from 'node:fs'
import path from 'node:path'
import { atomicWriteFile, atomicWriteJson, isUnder, sha256Hex } from './fsx.mjs'

export const ALLOWED_KEYS = [
  'IMG2_CHARACTER_NODE', 'IMG2_CHARACTER_BROWSER', 'IMG2_CHARACTER_BPY_PYTHON', 'IMG2_CHARACTER_THREE_ROOT',
  'IMG2_CHARACTER_THREE_SHA256', 'IMG2_BLENDER_PYTHON', 'IMG2THREEJS_VISION_PYTHON', 'PLAYWRIGHT_BROWSERS_PATH',
]
const PATH_KEYS = ALLOWED_KEYS.filter((k) => k !== 'IMG2_CHARACTER_THREE_SHA256')

// Same inventory forge/stage0_route/discovery.py `character_three_facts` hashes: sorted files, each
// {path, sha256}, canonical JSON (sorted keys, no spaces), sha256 of the UTF-8 bytes.
export const THREE_FILES = [
  'build/three.core.js', 'build/three.module.js', 'examples/jsm/loaders/GLTFLoader.js',
  'examples/jsm/utils/BufferGeometryUtils.js', 'examples/jsm/utils/SkeletonUtils.js', 'package.json',
]

export function threeInventoryDigest(root) {
  const files = [...THREE_FILES].sort().map((name) => {
    const p = path.join(root, name)
    const st = fs.lstatSync(p)
    if (!st.isFile()) throw new Error(name + ' is not a regular file')
    return { path: name, sha256: sha256Hex(fs.readFileSync(p)) }
  })
  const canonical = JSON.stringify({ files: files.map((f) => ({ path: f.path, sha256: f.sha256 })), kind: 'img2.character-three-package', version: 1 })
  return sha256Hex(Buffer.from(canonical, 'utf8'))
}

// A path the core may trust: absolute, exists, and its real location is inside the runtime tree.
export function checkSelectorPath(value, runtimeRoot) {
  if (typeof value !== 'string' || !path.isAbsolute(value)) return 'must be an absolute path'
  let real, realRoot
  try { real = fs.realpathSync.native(value) } catch { return 'does not exist' }
  try { realRoot = fs.realpathSync.native(runtimeRoot) } catch { return 'runtime root does not exist' }
  if (!isUnder(realRoot, real)) return 'resolves outside ' + runtimeRoot + ' (' + real + ')'
  return null
}

export function buildSelectors({ lockDigest, pluginsLockDigest, selectedPlugins, env, now = new Date() }) {
  const clean = {}
  for (const k of ALLOWED_KEYS) if (env[k] !== undefined) clean[k] = env[k]
  return { schema: 1, lockDigest, pluginsLockDigest, selectedPlugins: [...selectedPlugins].sort(), env: clean, createdAt: now.toISOString() }
}

export const selectorsPath = (runtimeRoot) => path.join(runtimeRoot, 'selectors.json')
export const envShPath = (runtimeRoot) => path.join(runtimeRoot, 'env.sh')

export function writeSelectors(runtimeRoot, selectors) {
  atomicWriteJson(selectorsPath(runtimeRoot), selectors, 0o600)
}

const shq = (s) => "'" + String(s).replace(/'/g, "'\\''") + "'"

export function writeEnvSh(runtimeRoot, selectors, extra = {}) {
  const lines = [
    '# Generated by `img2 provision`; do not edit. Source it to use the provisioned runtime in a shell.',
    '# lockDigest ' + selectors.lockDigest,
    '# plugins    ' + selectors.selectedPlugins.join(' '),
  ]
  for (const [k, v] of Object.entries({ ...selectors.env, ...extra })) lines.push('export ' + k + '=' + shq(v))
  atomicWriteFile(envShPath(runtimeRoot), lines.join('\n') + '\n', 0o644)
}

// Re-validates a written selectors.json the way the core will read it. Returns a list of problems.
export function validateSelectorsFile(runtimeRoot, { lockDigest, pluginsLockDigest } = {}) {
  const file = selectorsPath(runtimeRoot)
  const problems = []
  let st
  try { st = fs.lstatSync(file) } catch { return ['selectors.json is missing at ' + file] }
  if (!st.isFile()) problems.push('selectors.json is not a regular file')
  if (typeof process.getuid === 'function' && st.uid !== process.getuid()) problems.push('selectors.json is not owned by the current user')
  if ((st.mode & 0o777) !== 0o600) problems.push('selectors.json mode is ' + (st.mode & 0o777).toString(8) + ', expected 600')
  let doc
  try { doc = JSON.parse(fs.readFileSync(file, 'utf8')) } catch (e) { return [...problems, 'selectors.json is not valid JSON: ' + e.message] }
  if (doc.schema !== 1) problems.push('schema must be 1')
  if (lockDigest && doc.lockDigest !== lockDigest) problems.push('lockDigest ' + String(doc.lockDigest).slice(0, 12) + ' differs from the installed harness lock ' + lockDigest.slice(0, 12))
  if (pluginsLockDigest && doc.pluginsLockDigest !== pluginsLockDigest) problems.push('pluginsLockDigest ' + String(doc.pluginsLockDigest).slice(0, 12) + ' differs from the installed harness plugins lock ' + pluginsLockDigest.slice(0, 12))
  if (!Array.isArray(doc.selectedPlugins)) problems.push('selectedPlugins must be an array')
  if (typeof doc.env !== 'object' || doc.env === null) return [...problems, 'env must be an object']
  for (const [k, v] of Object.entries(doc.env)) {
    if (!ALLOWED_KEYS.includes(k)) { problems.push('env key ' + k + ' is not allowed'); continue }
    if (k === 'IMG2_CHARACTER_THREE_SHA256') { if (!/^[0-9a-f]{64}$/.test(v)) problems.push(k + ' must be 64 lowercase hex'); continue }
    const why = checkSelectorPath(v, runtimeRoot)
    if (why) problems.push(k + ': ' + why)
  }
  if (doc.env.IMG2_CHARACTER_THREE_ROOT && /^[0-9a-f]{64}$/.test(doc.env.IMG2_CHARACTER_THREE_SHA256 ?? '')) {
    try {
      const actual = threeInventoryDigest(doc.env.IMG2_CHARACTER_THREE_ROOT)
      if (actual !== doc.env.IMG2_CHARACTER_THREE_SHA256) problems.push('IMG2_CHARACTER_THREE_SHA256 does not match the files under IMG2_CHARACTER_THREE_ROOT (actual ' + actual + ')')
    } catch (e) { problems.push('Three inventory cannot be hashed: ' + e.message) }
  } else if (doc.env.IMG2_CHARACTER_THREE_ROOT || doc.env.IMG2_CHARACTER_THREE_SHA256) {
    problems.push('IMG2_CHARACTER_THREE_ROOT and IMG2_CHARACTER_THREE_SHA256 must be set together')
  }
  return problems
}

